var tmpl = template.Must(template.New("resource").Parse(fileTemplate))

// renderResource renders r into formatted Go source. The template above is
// deliberately simple enough to always produce syntactically valid Go
// (field/method presence is template-conditional, never free-text), so
// format.Source should never actually fail here - but checking its error
// is cheap insurance against a future template edit that breaks that.
func renderResource(r resource) ([]byte, error) {
	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, r); err != nil {
		return nil, fmt.Errorf("executing template for %s: %w", r.PluralName, err)
	}
	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("formatting generated source for %s: %w\n%s", r.PluralName, err, buf.String())
	}
	return formatted, nil
}
